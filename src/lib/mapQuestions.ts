/** Grey reference places shown on zoomed-in Egypt maps so the student can orient themselves. */
export function contextRefs(m: MapQuestion): MapPoint[] {
  const cairo = { lon: 31.24, lat: 30.04, label: "القاهرة" };
  const [w, s, e, n] = m.fit;
  const zoomedOnEgypt =
    e - w < 15 && w <= cairo.lon && cairo.lon <= e && s <= cairo.lat && cairo.lat <= n;
  const near = (m.points ?? []).some(
    (p) => Math.abs(p.lon - cairo.lon) < 0.35 && Math.abs(p.lat - cairo.lat) < 0.35,
  );
  return zoomedOnEgypt && !near ? [cairo] : [];
}

/** Map questions for one subject (optionally one lesson). */
export function mapQuestionsFor(subject: string, lesson?: string) {
  return MAP_QUESTIONS.filter((m) => m.subject === subject && (!lesson || m.lesson === lesson));
}
